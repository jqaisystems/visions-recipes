"""Pack traced outlines into assets/outlines.js for the film.

py build.py <outlines.json> <order.json> <captions.json|-> <end.json> <out.js>
order.json lists the outline ids in film order. captions.json maps id -> caption text ("-" for none).
end.json is the outline the line finally settles on (here the JQ mark's outer path).
"""
import json, sys

import numpy as np

N = 400


def resample(pts, n=N):
    p = np.array(pts, float)
    q = np.vstack([p, p[:1]])
    t = np.concatenate([[0], np.cumsum(np.hypot(*np.diff(q, axis=0).T))])
    u = np.linspace(0, t[-1], n, endpoint=False)
    return np.round(np.stack([np.interp(u, t, q[:, 0]), np.interp(u, t, q[:, 1])], 1), 3).ravel().tolist()


if __name__ == "__main__":
    outlines = {o["id"]: o for o in json.load(open(sys.argv[1]))}
    order = json.load(open(sys.argv[2]))
    caps = {} if sys.argv[3] == "-" else json.load(open(sys.argv[3], encoding="utf-8"))
    end = json.load(open(sys.argv[4]))
    data = {
        "marks": [{"id": i, "caption": caps.get(i, ""), "pts": resample(outlines[i]["pts"])} for i in order],
        "end": resample(end["pts"]),
    }
    with open(sys.argv[5], "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build.py: one outline per mark, " + str(N) + " points each (x, y pairs).\n")
        f.write("window.OUTLINES = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print(len(order), "outlines ->", sys.argv[5])
